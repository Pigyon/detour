// errBlocked means a WAF or edge answered in the application's place.
//
// Like errUnanswered it is not a verdict. The difference is that the request
// did arrive somewhere: the operator is told how many probes were refused and
// by whom, because a run whose payloads were all blocked otherwise reads
// exactly like a clean target.
var errBlocked = errors.New("probe blocked by a waf or edge")

// maxBlockedProbes bounds how many refused probes a run keeps by URL. The count
// and the per-vendor tally stay exact past it; only the list stops growing.
const maxBlockedProbes = 1000

// blockSignature is one recognizable block page.
type blockSignature struct {
	vendor string
	// header matches when the named response header contains the value
	// (any value when the value is empty).
	header, headerValue string
	// body matches when the response body contains every listed string,
	// compared case-insensitively.
	body []string
}

// vendorCloudflare is named by four signatures.
const vendorCloudflare = "cloudflare"

// blockSignatures are the block pages of the WAFs and edges detour meets most.
// Ordered, not a map: the first match names the vendor, and a map would name a
// different one on every run for a page two signatures share.
var blockSignatures = []blockSignature{
	{vendor: vendorCloudflare, header: "cf-mitigated"},
	{vendor: vendorCloudflare, body: []string{vendorCloudflare, "attention required"}},
	{vendor: vendorCloudflare, body: []string{vendorCloudflare, "you have been blocked"}},
	{vendor: vendorCloudflare, body: []string{"error code: 1020"}},
	{vendor: "akamai", body: []string{"access denied", "reference #"}},
	{vendor: "aws-waf", header: "x-amzn-waf-action"},
	{vendor: "aws-waf", body: []string{"request blocked", "generated by cloudfront"}},
	{vendor: "imperva", header: "x-iinfo"},
	{vendor: "imperva", body: []string{"incapsula incident id"}},
	{vendor: "f5", body: []string{"the requested url was rejected", "support id"}},
	{vendor: "sucuri", header: "x-sucuri-block"},
	{vendor: "sucuri", body: []string{"sucuri website firewall"}},
	{vendor: "modsecurity", body: []string{"mod_security"}},
	{vendor: "modsecurity", body: []string{"modsecurity"}},
	{vendor: "azure-front-door", header: "x-azure-ref", body: []string{"the request is blocked"}},
}

// blockVendor reports whether a response is a block page and whose.
//
// Only refusals qualify. A 2xx or 3xx that happens to mention a vendor is the
// application answering, and a 5xx without a signature is the application
// failing, which the retry path already handles.
func blockVendor(resp *http.Response, body []byte) (string, bool) {
	if resp == nil || resp.StatusCode < http.StatusBadRequest {
		return "", false
	}

	lowered := strings.ToLower(string(body))

	for _, sig := range blockSignatures {
		if sig.matches(resp, lowered) {
			return sig.vendor, true
		}
	}

	// 406 is what ModSecurity's default rule set answers, and an application
	// almost never chooses it for a query string it dislikes.
	if resp.StatusCode == http.StatusNotAcceptable {
		return "unknown", true
	}

	return "", false
}

func (s blockSignature) matches(resp *http.Response, loweredBody string) bool {
	if s.header == "" && len(s.body) == 0 {
		return false
	}

	if s.header != "" {
		values := resp.Header.Values(s.header)
		if len(values) == 0 {
			return false
		}

		if s.headerValue != "" && !strings.Contains(strings.ToLower(strings.Join(values, ",")), s.headerValue) {
			return false
		}
	}

	for _, needle := range s.body {
		if !strings.Contains(loweredBody, needle) {
			return false
		}
	}

	return true
}

// endpointKey names the endpoint a URL reaches, without its query, so a probe
// can be compared with the baseline of the source it was built from.
func endpointKey(raw string) string {
	u, err := url.Parse(raw)
	if err != nil {
		return raw
	}

	return strings.ToLower(u.Scheme) + "://" + strings.ToLower(u.Host) + u.EscapedPath()
}

// hostKey names a URL's host, for probes whose own endpoint never had a
// baseline. The prefix keeps it apart from every endpointKey.
func hostKey(raw string) string {
	u, err := url.Parse(raw)
	if err != nil {
		return "host|" + raw
	}

	return "host|" + strings.ToLower(u.Host)
}

// loginWords are path segments that name a sign-in step.
var loginWords = map[string]struct{}{
	"login": {}, "log-in": {}, "log_in": {}, "logon": {}, "signin": {}, "sign-in": {}, "sign_in": {},
	"sso": {}, "cas": {}, "saml": {}, "oauth": {}, "oauth2": {}, "authorize": {}, "auth": {},
	"authenticate": {}, "session": {}, "sessions": {}, "logout": {}, "signout": {}, "sign-out": {},
}

// loginHostPrefixes are the first labels identity providers serve sign-in on.
var loginHostPrefixes = []string{"login.", "signin.", "sso.", "auth.", "accounts.", "idp.", "id."}

// isLoginURL reports whether a URL is a sign-in step: a sign-in path anywhere,
// or a host that only does identity.
func isLoginURL(u *url.URL) bool {
	if u == nil {
		return false
	}

	host := strings.ToLower(u.Hostname())
	for _, prefix := range loginHostPrefixes {
		if strings.HasPrefix(host, prefix) {
			return true
		}
	}

	for segment := range strings.SplitSeq(strings.ToLower(u.Path), "/") {
		segment = strings.TrimSuffix(strings.TrimSuffix(segment, ".php"), ".jsp")
		if _, ok := loginWords[segment]; ok {
			return true
		}
	}

	return false
}

// authWall reports whether a source's first answer is a login wall.
//
// A login page is never a wall. It is where post-login redirect parameters
// live, which is exactly the surface detour exists to test, so a source whose
// own path is a sign-in step is always attacked.
//
// A login redirect that carries one of the source's own parameter values is
// not a wall either: the value flows into the sign-in step, and the payloads
// sent to the source travel the same way. Skipping it would hide the class of
// bug a login wall is most likely to have.
func authWall(raw string, resp *http.Response) (model.AuthWall, bool) {
	source, err := url.Parse(raw)
	if err != nil || resp == nil {
		return model.AuthWall{}, false
	}

	switch resp.StatusCode {
	case http.StatusUnauthorized, http.StatusProxyAuthRequired:
		return model.AuthWall{URL: raw, Status: resp.StatusCode, Reason: "status"}, true
	}

	if resp.StatusCode < http.StatusMultipleChoices || resp.StatusCode >= http.StatusBadRequest {
		return model.AuthWall{}, false
	}

	if isLoginURL(source) {
		return model.AuthWall{}, false
	}

	loc := resp.Header.Get("Location")
	if loc == "" {
		return model.AuthWall{}, false
	}

	target, err := source.Parse(loc)
	if err != nil || !isLoginURL(target) || carriesSourceValue(source, loc) {
		return model.AuthWall{}, false
	}

	return model.AuthWall{URL: raw, Status: resp.StatusCode, Reason: "login redirect", Location: loc}, true
}

// minCarriedValue is the shortest parameter value worth looking for in a
// redirect. Anything shorter ("1", "en") turns up by accident.
const minCarriedValue = 3

// carriesSourceValue reports whether a redirect target still holds one of the
// source's parameter values, raw or percent-encoded.
func carriesSourceValue(source *url.URL, loc string) bool {
	decoded, err := url.QueryUnescape(loc)
	if err != nil {
		decoded = loc
	}

	for _, values := range source.Query() {
		for _, v := range values {
			if len(v) < minCarriedValue {
				continue
			}

			if strings.Contains(loc, v) || strings.Contains(decoded, v) ||
				strings.Contains(loc, url.QueryEscape(v)) {
				return true
			}
		}
	}

	return false
}
