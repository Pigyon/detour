func response(status int, headers map[string]string) *http.Response {
	h := http.Header{}
	for k, v := range headers {
		h.Set(k, v)
	}

	return &http.Response{StatusCode: status, Header: h, Body: http.NoBody}
}

func TestBlockVendor(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name    string
		status  int
		headers map[string]string
		body    string
		vendor  string
		blocked bool
	}{
		{"cloudflare header", 403, map[string]string{"Cf-Mitigated": "challenge"}, "", "cloudflare", true},
		{"cloudflare 1020", 403, nil, "error code: 1020", "cloudflare", true},
		{"cloudflare page", 403, nil, "<title>Attention Required! | Cloudflare</title>", "cloudflare", true},
		{"akamai", 403, nil, "<H1>Access Denied</H1> Reference #18.5f1d2017", "akamai", true},
		{"aws waf header", 403, map[string]string{"X-Amzn-Waf-Action": "block"}, "", "aws-waf", true},
		{"cloudfront waf page", 403, nil, "Request blocked. Generated by cloudfront (CloudFront)", "aws-waf", true},
		{"imperva", 403, nil, "Request unsuccessful. Incapsula incident ID: 123", "imperva", true},
		{"f5", 200, nil, "The requested URL was rejected. Your support ID is: 1", "", false},
		{"f5 refused", 400, nil, "The requested URL was rejected. Your support ID is: 1", "f5", true},
		{"sucuri", 403, map[string]string{"X-Sucuri-Block": "1"}, "", "sucuri", true},
		{"modsecurity page", 403, nil, "This error was generated by Mod_Security.", "modsecurity", true},
		{"406 without signature", 406, nil, "Not Acceptable!", "unknown", true},
		{"azure needs both", 403, map[string]string{"X-Azure-Ref": "x"}, "nope", "", false},
		{"azure front door", 403, map[string]string{"X-Azure-Ref": "x"}, "The request is blocked.", "azure-front-door", true},
		{"vendor named on a success page", 200, nil, "protected by cloudflare, attention required", "", false},
		{"redirect is never a block", 302, map[string]string{"Cf-Mitigated": "challenge"}, "", "", false},
		{"plain 403 is left to the baseline", 403, nil, "Forbidden", "", false},
		{"plain 500", 500, nil, "Internal Server Error", "", false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			resp := response(tt.status, tt.headers)

			t.Cleanup(func() { _ = resp.Body.Close() })

			vendor, blocked := blockVendor(resp, []byte(tt.body))
			assert.Equal(t, tt.blocked, blocked)
			assert.Equal(t, tt.vendor, vendor)
		})
	}
}

func TestIsLoginURL(t *testing.T) {
	t.Parallel()

	tests := []struct {
		raw  string
		want bool
	}{
		{"https://shop.test/account/login?return_to=/", true},
		{"https://shop.test/users/sign_in", true},
		{"https://shop.test/signin", true},
		{"https://shop.test/oauth2/authorize?client_id=x", true},
		{"https://shop.test/cas/login.jsp", true},
		{"https://login.microsoftonline.com/common/oauth2", true},
		{"https://accounts.shop.test/", true},
		{"https://shop.test/logout?next=/", true},
		{"https://shop.test/products/login-gift-card", false},
		{"https://shop.test/blog/authors", false},
		{"https://shop.test/", false},
	}

	for _, tt := range tests {
		t.Run(tt.raw, func(t *testing.T) {
			t.Parallel()

			u, err := url.Parse(tt.raw)
			require.NoError(t, err)
			assert.Equal(t, tt.want, isLoginURL(u))
		})
	}
}

// idpLogin is an identity provider's sign-in URL.
const idpLogin = "https://login.idp.test/oauth2/authorize?client_id=a"

func TestAuthWall(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		source   string
		status   int
		location string
		reason   string
		walled   bool
	}{
		{"401", "https://app.test/api/me?url=https://x.test/", 401, "", "status", true},
		{"407", "https://app.test/go?url=https://x.test/", 407, "", "status", true},
		{"401 on a login path still walls", "https://app.test/login?next=/", 401, "", "status", true},
		{"redirect to sign-in", "https://app.test/account?next=/orders", 302, "/users/sign_in", "login redirect", true},
		{"redirect to an idp", "https://app.test/dash?url=/home", 302, idpLogin, "login redirect", true},
		{"login redirect carrying the value", "https://app.test/account?next=/orders", 302, "/login?return_to=%2Forders", "", false},
		{"login redirect carrying the raw value", "https://app.test/go?url=https://x.test/", 302, "/login?r=https://x.test/", "", false},
		{"source is itself a login page", "https://app.test/login?next=/", 302, "/signin", "", false},
		{"redirect somewhere else", "https://app.test/go?url=/home", 302, "/home", "", false},
		{"200 is not a wall", "https://app.test/go?url=/home", 200, "", "", false},
		{"403 is not a wall", "https://app.test/go?url=/home", 403, "", "", false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			headers := map[string]string{}
			if tt.location != "" {
				headers["Location"] = tt.location
			}

			resp := response(tt.status, headers)

			t.Cleanup(func() { _ = resp.Body.Close() })

			wall, walled := authWall(tt.source, resp)
			assert.Equal(t, tt.walled, walled)

			if tt.walled {
				assert.Equal(t, tt.reason, wall.Reason)
				assert.Equal(t, tt.status, wall.Status)
				assert.Equal(t, tt.source, wall.URL)
				assert.Equal(t, tt.location, wall.Location)
			}
		})
	}
}

